// The usual currency for a country, or null for a name that isn't in the list.
export function currencyForCountry(country: string): string | null {
  const wanted = country.trim().toLowerCase();
  return COUNTRIES.find((item) => item.name.toLowerCase() === wanted)?.currency ?? null;
}
