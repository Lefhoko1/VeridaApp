const kindOptions = (Object.keys(SUGGESTION_KIND_LABELS) as SuggestionKind[]).map((value) => ({ value, label: SUGGESTION_KIND_LABELS[value] }));

const RULES_NOTE = 'The AI service was not available, so these come from Verida’s built-in planning rules.';

// Section 4.6: asking Verida for help. Nothing is created here: the result is a suggestion for
// the person to review.
export function usePlanAssistViewModel({ kind, goalId, onDone }: { kind?: SuggestionKind; goalId?: string; onDone: (suggestionId: string) => void }) {
  const { business, can, scope, goals } = usePlanQueries();
  const { advisor } = usePlanDependencies();
  const feedback = useFeedback();
  const queryClient = useQueryClient();
  const [chosenKind, setKind] = useState<SuggestionKind>(kind ?? (goalId ? 'goal_breakdown' : 'weekly_plan'));
  const [chosenGoal, setGoal] = useState(goalId ?? '');
  const [request, setRequest] = useState('');

  const ask = useMutation({
    mutationFn: () => advisor.suggest({ businessId: business.id, kind: chosenKind, goalId: chosenKind === 'goal_breakdown' ? chosenGoal : null, request: request.trim() || null }),
    onSuccess: async (result) => {
      await queryClient.invalidateQueries({ queryKey: [...scope, 'suggestions'] });
      if (!result.suggestionId) {
        feedback.success(result.source === 'rules' ? `${RULES_NOTE} They found nothing to suggest right now.` : 'Nothing to suggest right now.');
        return;
      }
      if (result.source === 'rules') feedback.success(RULES_NOTE);
      onDone(result.suggestionId);
    },
    onError: (error) => feedback.error(errorMessage(error)),
  });

  const openGoals = (goals.data ?? []).filter((goal) => ['active', 'at_risk', 'on_hold'].includes(goal.status));
  return {
    canAsk: can('plan.tasks'),
    kind: chosenKind,
    kindOptions,
    setKind: (value: string) => setKind(value as SuggestionKind),
    goal: chosenGoal,
    goalOptions: openGoals.map((goal) => ({ value: goal.id, label: goal.title })),
    setGoal,
    request,
    setRequest,
    requestLabel: chosenKind === 'request' ? 'What would you like help with?' : chosenKind === 'weekly_plan' ? 'When are you available? (optional)' : 'Anything Verida should know? (optional)',
    asking: ask.isPending,
    submit() {
      if (chosenKind === 'goal_breakdown' && !chosenGoal) {
        feedback.error('Choose a goal to break into steps.');
        return;
      }
      if (chosenKind === 'request' && !request.trim()) {
        feedback.error('Say what you would like help with.');
        return;
      }
      ask.mutate();
    },
  };
}

export type EditDraft = { title: string; dueOn: string; priority: string; startsOn: string; startTime: string; endTime: string };

const toDraft = (action: SuggestedAction): EditDraft => {
  const p = action.finalPayload ?? action.payload;
  return { title: p.title ?? '', dueOn: p.due_on ?? '', priority: p.priority ?? 'normal', startsOn: p.starts_on ?? '', startTime: p.start_time ?? '', endTime: p.end_time ?? '' };
};

// Only the fields that changed, and only those the action allows.
function editsFrom(action: SuggestedAction, draft: EditDraft): ActionEdits {
  const before = toDraft(action);
  const edits: ActionEdits = {};
  if (action.type !== 'update_task' && draft.title.trim() !== before.title) edits.title = draft.title.trim();
  if (draft.dueOn !== before.dueOn && action.type !== 'create_event' && action.type !== 'create_goal') edits.due_on = draft.dueOn || undefined;
  if (draft.priority !== before.priority && (action.type === 'create_task' || action.type === 'update_task')) edits.priority = draft.priority as ActionEdits['priority'];
  if (action.type === 'create_event') {
    if (draft.startsOn !== before.startsOn) edits.starts_on = draft.startsOn;
    if (draft.startTime !== before.startTime) edits.start_time = draft.startTime || undefined;
    if (draft.endTime !== before.endTime) edits.end_time = draft.endTime || undefined;
  }
  return edits;
}

const STATUS_WORDS: Record<SuggestedAction['status'], string> = { proposed: 'Waiting for you', accepted: 'Added', edited: 'Added with your changes', dismissed: 'Dismissed' };

// Section 4.6: one suggestion, clearly labelled, with each action accepted, edited, dismissed or
// regenerated by a person. Its sources, period, assumptions and model are shown.
export function useSuggestionViewModel(suggestionId: string, { onReplaced }: { onReplaced: (id: string) => void }) {
  const { plan, business, can, scope, goals } = usePlanQueries();
  const { advisor } = usePlanDependencies();
  const feedback = useFeedback();
  const queryClient = useQueryClient();
  const suggestion = useQuery({ queryKey: [...scope, 'suggestions', suggestionId], queryFn: () => plan.getSuggestion(suggestionId) });
  const [editing, setEditing] = useState<string | null>(null);
  const [draft, setDraft] = useState<EditDraft | null>(null);

  const refresh = () => queryClient.invalidateQueries({ queryKey: scope });
  const report = { onError: (error: unknown) => feedback.error(errorMessage(error)) };

  const accept = useMutation({
    mutationFn: ({ actionId, edits }: { actionId: string; edits: ActionEdits }) => plan.acceptAction(actionId, edits),
    onSuccess: async () => {
      setEditing(null);
      await refresh();
      feedback.success('Added to your plan.');
    },
    ...report,
  });
  const dismiss = useMutation({ mutationFn: (actionId: string) => plan.dismissAction(actionId), onSuccess: refresh, ...report });
  const dismissAll = useMutation({
    mutationFn: () => plan.dismissSuggestion(suggestionId),
    onSuccess: async () => {
      await refresh();
      feedback.success('Suggestion dismissed.');
    },
    ...report,
  });
  const regenerate = useMutation({
    mutationFn: (current: Suggestion) => advisor.suggest({ businessId: business.id, kind: current.kind, goalId: current.goalId, request: current.request }),
    onSuccess: async (result) => {
      await refresh();
      if (result.source === 'rules') feedback.success(RULES_NOTE);
      if (result.suggestionId) onReplaced(result.suggestionId);
      else feedback.success('Nothing new to suggest right now.');
    },
    ...report,
  });

  const current = suggestion.data;
  const goalTitle = (id: string) => (goals.data ?? []).find((goal) => goal.id === id)?.title ?? null;
  const live = current?.status === 'open';

  return {
    loading: suggestion.isPending,
    error: suggestion.error ? errorMessage(suggestion.error) : null,
    suggestion: current ?? null,
    kindLabel: current ? SUGGESTION_KIND_LABELS[current.kind] : '',
    // Section 4.6: generated content is labelled as a suggestion, with where it came from.
    origin: current
      ? current.generator === 'ai'
        ? `Drafted by Verida's AI${current.model ? ` (${current.model})` : ''} on ${formatDate(current.generatedAt.slice(0, 10))}. Check it before you accept.`
        : `From Verida's built-in planning rules, on ${formatDate(current.generatedAt.slice(0, 10))}.`
      : '',
    period: current?.periodStart && current.periodEnd ? `${formatDate(current.periodStart)} to ${formatDate(current.periodEnd)}` : null,
    statusNote:
      current?.status === 'superseded' ? 'A newer suggestion replaced this one.' : current?.status === 'dismissed' ? 'This suggestion was dismissed.' : current?.status === 'decided' ? 'Everything in this suggestion has been decided.' : null,
    actions: (current?.actions ?? []).map((action) => ({
      ...describeAction(action, goalTitle, formatDate),
      id: action.id,
      type: action.type,
      why: action.why,
      status: action.status,
      statusLabel: STATUS_WORDS[action.status],
      open: action.status === 'proposed' && live,
      canDecide: can(actionNeedsGoalsPermission(action.type) ? 'plan.goals' : 'plan.tasks'),
      createdTaskId: action.createdTaskId,
      createdGoalId: action.createdGoalId ?? (action.type === 'create_milestone' ? (action.payload.goal_id ?? null) : null),
      createdEventId: action.createdEventId,
    })),
    sources: (current?.sources ?? []).map((source) => ({ ...source, openable: source.type === 'goal' || source.type === 'task' })),
    busy: accept.isPending || dismiss.isPending,
    accept: (actionId: string) => accept.mutate({ actionId, edits: {} }),
    dismiss: (actionId: string) => dismiss.mutate(actionId),
    editing,
    draft,
    startEdit(actionId: string) {
      const action = current?.actions.find((item) => item.id === actionId);
      if (!action) return;
      setEditing(actionId);
      setDraft(toDraft(action));
    },
    cancelEdit: () => setEditing(null),
    setDraftField: (field: keyof EditDraft, value: string) => setDraft((existing) => (existing ? { ...existing, [field]: value } : existing)),
    saveEdit() {
      const action = current?.actions.find((item) => item.id === editing);
      if (!action || !draft) return;
      accept.mutate({ actionId: action.id, edits: editsFrom(action, draft) });
    },
    priorityOptions: PRIORITY_OPTIONS,
    canRegenerate: live && can('plan.tasks'),
    regenerating: regenerate.isPending,
    regenerate: () => current && regenerate.mutate(current),
    canDismissAll: live && can('plan.tasks'),
    dismissAll: () => dismissAll.mutate(),
  };
}

// The suggestions panel on the overview (section 1 wireframe), kept apart from confirmed work.
export function useSuggestionsPanelViewModel() {
  const { plan, business, can, scope, goals, enabled } = usePlanQueries();
  const feedback = useFeedback();
  const queryClient = useQueryClient();
  const list = useQuery({ queryKey: [...scope, 'suggestions', 'open'], queryFn: () => plan.listSuggestions(business.id), enabled });
  const refresh = () => queryClient.invalidateQueries({ queryKey: scope });
  const accept = useMutation({
    mutationFn: (actionId: string) => plan.acceptAction(actionId, {}),
    onSuccess: async () => {
      await refresh();
      feedback.success('Added to your plan.');
    },
    onError: (error) => feedback.error(errorMessage(error)),
  });
  const dismiss = useMutation({ mutationFn: (actionId: string) => plan.dismissAction(actionId), onSuccess: refresh, onError: (error) => feedback.error(errorMessage(error)) });
  const goalTitle = (id: string) => (goals.data ?? []).find((goal) => goal.id === id)?.title ?? null;
  const open = (list.data ?? []).filter((suggestion) => suggestion.actions.some((action) => action.status === 'proposed'));
  const first = open[0];
  const next = first?.actions.find((action) => action.status === 'proposed');

  return {
    canAsk: can('plan.tasks'),
    hasAny: open.length > 0,
    top:
      first && next
        ? {
            suggestionId: first.id,
            title: first.title,
            generator: first.generator,
            explanation: first.explanation,
            action: { id: next.id, ...describeAction(next, goalTitle, formatDate), why: next.why, canAccept: can(actionNeedsGoalsPermission(next.type) ? 'plan.goals' : 'plan.tasks') },
            remaining: first.actions.filter((action) => action.status === 'proposed').length,
          }
        : null,
    others: open.slice(1, 3).map((suggestion) => ({ id: suggestion.id, title: suggestion.title, waiting: suggestion.actions.filter((action) => action.status === 'proposed').length })),
    busy: accept.isPending || dismiss.isPending,
    accept: (actionId: string) => accept.mutate(actionId),
    dismiss: (actionId: string) => dismiss.mutate(actionId),
  };
}

// Sections 3 and 13: what an owner decides for the whole business.
export function usePlanSettingsViewModel({ onDone }: { onDone: () => void }) {
  const { plan, business, can, scope } = usePlanQueries();
  const feedback = useFeedback();
  const queryClient = useQueryClient();
  const settings = useQuery({ queryKey: [...scope, 'settings'], queryFn: () => plan.getSettings(business.id) });
  // Only what the person changed, on top of the saved settings.
  const [changes, setChanges] = useState<Partial<PlanSettings>>({});
  const draft = settings.data ? { ...settings.data, ...changes } : null;

  const save = useMutation({
    mutationFn: (next: PlanSettings) => plan.saveSettings(business.id, next),
    onSuccess: async () => {
      await queryClient.invalidateQueries({ queryKey: scope });
      feedback.success('Plan settings saved.');
      onDone();
    },
    onError: (error) => feedback.error(errorMessage(error)),
  });

  return {
    loading: settings.isPending || !draft,
    error: settings.error ? errorMessage(settings.error) : null,
    canEdit: can('business.manage'),
    settings: draft,
    set: <K extends keyof PlanSettings>(key: K, value: PlanSettings[K]) => setChanges((current) => ({ ...current, [key]: value })),
    reminderTimes: ['06:00', '07:00', '08:00', '09:00', '12:00', '17:00', '18:00'].map((time) => ({ value: time, label: time })),
    saving: save.isPending,
    submit: () => draft && save.mutate(draft),
  };
}
